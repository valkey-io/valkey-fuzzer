"""Tables in the docs generated from what they list: docs/components.md lists every component's declared events,
evidence, and state changes, and docs/bug-zoo.md every bug zoo case.

On a mismatch the assertion message holds the table to paste between the
markers.
"""

from pathlib import Path

import yaml

from valkey_fuzzer.components import component_registrations

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "components.md"
BEGIN = "<!-- BEGIN declarations: generated by tests/test_docs_declarations.py -->"
END = "<!-- END declarations -->"
ZOO_DOC = ROOT / "docs" / "bug-zoo.md"
ZOO_BEGIN = "<!-- BEGIN cases: generated by tests/test_docs_declarations.py -->"
ZOO_END = "<!-- END cases -->"


def _names(names, many=()):
    rendered = [f"`{name.replace('{id}', '<id>')}`" + (" (many)" if name in many else "") for name in sorted(names)]
    return "<br>".join(rendered) or "none"


def declarations_table() -> str:
    rows = ["| Component | Publishes | Emits | Changes |", "| --- | --- | --- | --- |"]
    for registration in sorted(component_registrations(), key=lambda item: item.component_id):
        declares = registration.declares
        many = {name for name, item in declares.evidence.items() if item.many}
        rows.append(
            f"| `{registration.component_id}` | {_names(declares.events)} | {_names(declares.evidence, many)} "
            f"| {_names(declares.changes)} |"
        )
    return "\n".join(rows)


def test_the_component_reference_lists_every_declaration():
    text = DOC.read_text(encoding="utf-8")
    documented = text.split(BEGIN, 1)[1].split(END, 1)[0].strip()

    assert documented == declarations_table(), "regenerate the table:\n" + declarations_table()


def zoo_table() -> str:
    rows = [
        "| Case | Level | What is broken | What catches it | Broken runs | Must detect |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for case in sorted(path.parent for path in (ROOT / "zoo").glob("*/case.yaml")):
        document = yaml.safe_load((case / "case.yaml").read_text(encoding="utf-8"))
        level = "build" if (case / "patch.diff").exists() else "configuration"
        rows.append(
            f"| `{case.name}` | {level} | {document['description']} | {document['catches']} "
            f"| {document['runs']} | {document['min_detection_rate']:.0%} |"
        )
    return "\n".join(rows)


def test_the_bug_zoo_page_lists_every_case():
    text = ZOO_DOC.read_text(encoding="utf-8")
    documented = text.split(ZOO_BEGIN, 1)[1].split(ZOO_END, 1)[0].strip()

    assert documented == zoo_table(), "regenerate the table:\n" + zoo_table()
